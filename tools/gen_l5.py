#!/usr/bin/env python3
"""gen_l5.py: generate theories/L5/GenCatalog.v (data only) from the component JSON descriptors of the pin.

Input: docs/component-json/catalog-components.tar.xz, a tar of the 415 catalog/camel-catalog/src/generated/resources/
org/apache/camel/catalog/components/*.json files at the pin (stored compressed: 13.5 MB of JSON, 0.65 MB as tar.xz).
Output: one Rocq record per component (Model.comp) and per endpoint option (Model.opt), each option with a comment
citing its JSON line, and the list [catalog]. Only the fields the rules use are kept (see Model.v).
Run: python3 -I tools/gen_l5.py  (deterministic; prints a summary to stderr)."""
import io, json, os, re, sys, tarfile

S = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TAR = os.path.join(S, 'docs/component-json/catalog-components.tar.xz')
OUT = os.path.join(S, 'theories/L5/GenCatalog.v')


def q(s):
    s = str(s)
    assert all(32 <= ord(c) < 127 for c in s), repr(s)
    return '"' + s.replace('"', '""') + '"'


def opt_s(x):
    return 'None' if x is None else f'(Some {q(x)})'


def b(x):
    return 'true' if x else 'false'


def deftext(v):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    return str(v)


TY = {'string': 'TyString', 'boolean': 'TyBoolean', 'integer': 'TyInteger', 'number': 'TyNumber',
      'duration': 'TyDuration', 'enum': 'TyEnum', 'object': 'TyObject', 'array': 'TyArray'}
JT = {'java.lang.String': 'JString', 'int': 'JPInt', 'java.lang.Integer': 'JInt', 'long': 'JPLong',
      'java.lang.Long': 'JLong', 'boolean': 'JPBool', 'java.lang.Boolean': 'JBool', 'double': 'JPDouble',
      'java.lang.Double': 'JDouble', 'java.time.Duration': 'JDuration'}


def jt(o):
    j = o['javaType']
    if j in JT:
        return JT[j]
    # an option of type enum whose javaType is a class: a Java enum, unless it is an SPI interface
    if o['type'] == 'enum' and '.spi.' not in j and '<' not in j:
        return 'JEnum'
    return 'JOther'


def ident(stem):
    return 'c_' + re.sub(r'[^A-Za-z0-9_]', '_', stem)


def main():
    comps = []
    with tarfile.open(TAR) as t:
        for m in sorted(t.getmembers(), key=lambda m: m.name):
            if not m.name.endswith('.json'):
                continue
            text = t.extractfile(m).read().decode('utf-8')
            comps.append((os.path.basename(m.name), text))
    out = ['(** * L5 generated catalog: the option tables of all components at the pin (DATA, no rules).',
           '    GENERATED by tools/gen_l5.py from docs/component-json/catalog-components.tar.xz; do not edit.',
           '    Each option row cites its JSON line as [CJ:<file>.<line>]. *)',
           'From Stdlib Require Import String List.', 'From CamelSpec.L5 Require Import Model.',
           'Import ListNotations.', 'Open Scope string_scope.', '']
    enums = {}
    nopt = 0
    names = []
    syn_bad = []
    for fname, text in comps:
        j = json.loads(text)
        c = j['component']
        lines = text.split('\n')
        pstart = next(i for i, l in enumerate(lines) if l.startswith('  "properties"'))
        rows = []
        for k, o in j.get('properties', {}).items():
            ln = next(i for i in range(pstart, len(lines)) if lines[i].lstrip().startswith(json.dumps(k) + ':'))
            e = o.get('enum', [])
            if len(e) > 3:
                key = tuple(e)
                if key not in enums:
                    enums[key] = f'e{len(enums)}'
                es = enums[key]
            else:
                es = '[' + '; '.join(q(x) for x in e) + ']'
            rows.append(f'  mkO {q(k)} {"KPath" if o["kind"] == "path" else "KParam"} {TY[o["type"]]} {jt(o)} '
                        f'{b(o.get("required"))} {opt_s(deftext(o["defaultValue"]) if "defaultValue" in o else None)} '
                        f'{es} {b(o.get("multiEnum"))} {opt_s(o.get("prefix"))} {b(o.get("multiValue"))} '
                        f'{opt_s(o.get("optionalPrefix"))} {b(o.get("secret"))} (* .{ln + 1} *)')
            nopt += 1
        sl = next(i for i, l in enumerate(lines) if l.lstrip().startswith('"syntax"')) + 1
        idn = ident(fname[:-5])
        names.append(idn)
        assert ',' not in c['scheme'], fname
        pathnames = [k for k, o in j.get('properties', {}).items() if o['kind'] == 'path']
        synnames = re.findall(r'[A-Za-z0-9_]+', c['syntax'].split(':', 1)[1]) if ':' in c['syntax'] else []
        if sorted(synnames) != sorted(pathnames):
            syn_bad.append((fname, c['syntax'], pathnames))
        out.append(f'(* [CJ:{fname}.{sl}] *)')
        out.append(f'Definition {idn} : comp := mkComp {q(fname)} {q(c["scheme"])} {q(c["syntax"])} '
                   f'{b(c.get("lenientProperties"))} {b(c.get("api"))} '
                   f'[{"; ".join(q(k) for k, o in j.get("componentProperties", {}).items() if o.get("required") and "defaultValue" not in o)}] [')
        out.append(';\n'.join(rows))
        out.append('].')
    hdr = []
    for key, n in enums.items():
        hdr.append(f'Definition {n} : list string := [' + '; '.join(q(x) for x in key) + '].')
    i = out.index('') + 1
    out[i:i] = hdr + ['']
    out.append('')
    out.append('Definition catalog : list comp := [' + '; '.join(names) + '].')
    with open(OUT, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print(f'{len(comps)} components, {nopt} options, {len(enums)} shared enum lists; syntax names that are not '
          f'exactly the path options: {len(syn_bad)}', file=sys.stderr)
    for x in syn_bad:
        print('  ', x, file=sys.stderr)


main()
