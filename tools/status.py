#!/usr/bin/env python3
"""status.py: print STATUS.md from the sources and the runs (make status). Counts, per layer: rule tags by provenance
(CONVENTIONS.md), distinct UNSPECIFIED reasons in the rules, documented examples proved, theorems, differential
cases run / agree / mismatch, and the L2 rules never hit by a compared case. Nothing here is hand-maintained."""
import glob, os, re, subprocess
from collections import defaultdict

S = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(S)
files = sorted(glob.glob('theories/**/*.v', recursive=True))
layer = lambda f: f.split('/')[1]
tags = defaultdict(lambda: defaultdict(int))
rules = defaultdict(set)
uns = defaultdict(set)
examples = defaultdict(int)
theorems = defaultdict(list)
UNS = re.compile(r'\b(?:[A-Z][a-z]?Uns0?|Uns0|RUns|BUns|OUns|EUns|PUns|SUns|CUns|LUns|AgUns)\s+"([^"]*)"')
for f in files:
    L = layer(f)
    src = open(f).read()
    for m in re.finditer(r'\(\*! R (\S+) (DOC-BUG|DOC|CODE|MAINTAINER|FIX)\b', src):
        RL = m.group(1).split('.')[0]          # the layer is the rule id's prefix (L3 rules live in L2/Route.v)
        rules[RL].add(m.group(1)); tags[RL][m.group(2)] += 1
    for m in UNS.finditer(src):
        if m.group(1) != 'fuel': uns[L].add(m.group(1))
    examples[L] += len(re.findall(r'^Example doc_', src, re.M))
    theorems[L] += re.findall(r'^(?:Theorem|Lemma) (\w+)', src, re.M)

runs = defaultdict(lambda: [0, 0, 0, 0, 0, 0])   # cases, agree, mismatch, setup-error, unspec, hangs
cur = open('oracle/route/BUILD-INFO').read() if os.path.exists('oracle/route/BUILD-INFO') else None
superseded = set()
for f in glob.glob('runs/*/*.summary'):
    bi = os.path.join(os.path.dirname(f), 'ORACLE-BUILD-INFO')
    if not os.path.exists(bi) or open(bi).read() != cur:
        superseded.add(os.path.basename(os.path.dirname(f))); continue
    for line in open(f):
        m = re.match(r'ALL cases (\d+) sends-compared \d+ agree (\d+) mismatch (\d+) setup-error (\d+) unspec-sends (\d+)(?: hangs (\d+))?', line)
        if m:
            md = os.path.join(os.path.dirname(f), 'MODE')
            r = runs['L2 routes, ' + (open(md).read().strip() if os.path.exists(md) else 'doc') + ' mode']
            for i, v in enumerate(int(g or 0) for g in m.groups()): r[i] += v
# L5 runs (their own summaries: harness/l5)
for d in ('runs/l5-doc', 'runs/l5-real'):
    for f in glob.glob(d + '/*.l5summary'):
        for line in open(f):
            m = re.match(r'ALL cases (\d+) compared \d+ agree (\d+) mismatch (\d+) setup-error (\d+) unspec (\d+)', line)
            if m:
                r = runs['L5 endpoints/catalog, ' + ('real' if d.endswith('real') else 'doc') + ' mode']
                for i, v in enumerate(map(int, m.groups())): r[i] += v
# L4 runs (harness/l4): counted only when made with the current L4 oracle build
cur4 = open('oracle/l4/BUILD-INFO').read() if os.path.exists('oracle/l4/BUILD-INFO') else None
for d in ('runs/l4-doc', 'runs/l4-real'):
    bi = os.path.join(d, 'L4-ORACLE-BUILD-INFO')
    if not os.path.exists(bi) or open(bi).read() != cur4: continue
    for f in glob.glob(d + '/*.l4summary'):
        for line in open(f):
            m = re.match(r'ALL cases (\d+) ops-run \d+ ops-compared \d+ agree (\d+) mismatch (\d+) setup-error (\d+) unspec-cases (\d+)', line)
            if m:
                r = runs['L4 lifecycle, ' + ('real' if d.endswith('real') else 'doc') + ' mode']
                for i, v in enumerate(map(int, m.groups())): r[i] += v
hits = defaultdict(int)
for f in glob.glob('runs/*/*.hits'):
    if os.path.basename(os.path.dirname(f)) in superseded: continue
    for line in open(f):
        k, n = line.split('\t'); hits[k] += int(n)
never = sorted(r for r in rules['L2'] | rules['L3'] if hits.get(r, 0) == 0 and not r.endswith('stop-propagates'))
commit = subprocess.run(['git', 'log', '-1', '--format=%h %cd', '--date=short'], capture_output=True, text=True).stdout.strip()

print('# STATUS (generated by tools/status.py; do not edit by hand)\n')
print(f'Spec commit {commit}; Camel under test: PIN ({open("PIN").readline().split()[1]}).\n')
print('| Layer | rules | DOC | CODE | FIX | DOC-BUG | UNSPECIFIED reasons | doc examples proved | theorems |')
print('|---|---|---|---|---|---|---|---|---|')
for L in ['Common', 'L0', 'L1', 'L2', 'L3', 'L4', 'L5', 'L6']:
    t = tags[L]
    print(f'| {L} | {len(rules[L])} | {t["DOC"]} | {t["CODE"]} | {t["FIX"]} | {t["DOC-BUG"]} | {len(uns[L])} | '
          f'{examples[L]} | {", ".join(theorems[L]) or "-"} |')
print('\n## Differential runs\n')
print('| harness | cases | agree | mismatch | setup errors | hangs | UNSPECIFIED sends (counted, not compared) |')
print('|---|---|---|---|---|---|---|')
for k, r in runs.items():
    print(f'| {k} | {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[5] if len(r) > 5 else 0} | {r[4]} |')
print(f'\nOnly runs made with the current oracle build (oracle/route/BUILD-INFO) are counted; superseded runs: '
      f'{", ".join(sorted(superseded)) or "none"} (their history is in notes/main.md).')
for f in sorted(glob.glob('runs/*.md')):
    print(f'\nSee also {f}.')
print('\n## Coverage of the L2/L3 rules by compared cases\n')
print(', '.join(f'{k} {v}' for k, v in sorted(hits.items(), key=lambda kv: kv[1])) or '-')
print(f'\nNever hit: {", ".join(never) or "none"}.')
print('\n## Honest scope\n')
print(open('notes/scope.md').read() if os.path.exists('notes/scope.md') else '-')
